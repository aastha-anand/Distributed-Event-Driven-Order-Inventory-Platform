
-- V1: Create the core inventory schema

-- 1. Products table
CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          sku VARCHAR(100) NOT NULL UNIQUE,
                          name VARCHAR(255) NOT NULL,
                          price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
                          active BOOLEAN NOT NULL DEFAULT TRUE,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Inventory table: one row per product
CREATE TABLE inventory (
                           product_id BIGINT PRIMARY KEY
                               REFERENCES products(id),
                           on_hand INTEGER NOT NULL DEFAULT 0 CHECK (on_hand >= 0),
                           reserved INTEGER NOT NULL DEFAULT 0,
                           version BIGINT NOT NULL DEFAULT 0,

                           CONSTRAINT chk_inventory_reserved
                               CHECK (reserved >= 0 AND reserved <= on_hand)
);

-- 3. Inventory movement audit table
CREATE TABLE inventory_movements (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     product_id BIGINT NOT NULL REFERENCES products(id),
                                     movement_type VARCHAR(30) NOT NULL,
                                     on_hand_delta INTEGER NOT NULL DEFAULT 0,
                                     reserved_delta INTEGER NOT NULL DEFAULT 0,
                                     reference VARCHAR(150),
                                     created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT chk_movement_type CHECK (
                                         movement_type IN (
                                                           'RECEIPT',
                                                           'ADJUSTMENT',
                                                           'RESERVATION',
                                                           'RELEASE',
                                                           'SALE'
                                             )
                                         ),

                                     CONSTRAINT chk_movement_delta
                                         CHECK (on_hand_delta <> 0 OR reserved_delta <> 0)
);

-- Index for finding a product's stock movement history
CREATE INDEX idx_inventory_movements_product_created
    ON inventory_movements (product_id, created_at DESC);
