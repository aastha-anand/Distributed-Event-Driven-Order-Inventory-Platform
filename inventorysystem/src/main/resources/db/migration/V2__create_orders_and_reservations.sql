CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        idempotency_key VARCHAR(150) NOT NULL UNIQUE,
                        request_hash VARCHAR(64) NOT NULL,
                        status VARCHAR(30) NOT NULL DEFAULT 'CREATED',
                        payment_status VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED',
                        total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
                        expires_at TIMESTAMPTZ NOT NULL,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                        CONSTRAINT chk_order_status CHECK (
                            status IN (
                                       'CREATED', 'RESERVED', 'CONFIRMED',
                                       'CANCELLED', 'EXPIRED', 'PAYMENT_FAILED'
                                )
                            ),
                        CONSTRAINT chk_payment_status CHECK (
                            payment_status IN (
                                               'NOT_STARTED', 'PENDING', 'SUCCEEDED', 'FAILED'
                                )
                            )
);

CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             order_id BIGINT NOT NULL REFERENCES orders(id),
                             product_id BIGINT NOT NULL REFERENCES products(id),
                             quantity INTEGER NOT NULL CHECK (quantity > 0),
                             unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
                             CONSTRAINT uq_order_product UNIQUE (order_id, product_id)
);

CREATE TABLE inventory_reservations (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        order_item_id BIGINT NOT NULL UNIQUE REFERENCES order_items(id),
                                        product_id BIGINT NOT NULL REFERENCES products(id),
                                        quantity INTEGER NOT NULL CHECK (quantity > 0),
                                        status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                                        expires_at TIMESTAMPTZ NOT NULL,
                                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                        CONSTRAINT chk_reservation_status CHECK (
                                            status IN ('ACTIVE', 'RELEASED', 'CONSUMED', 'EXPIRED')
                                            )
);

CREATE INDEX idx_orders_status_expiry
    ON orders (status, expires_at);

CREATE INDEX idx_reservations_expiry
    ON inventory_reservations (status, expires_at);

CREATE INDEX idx_order_items_order_id
    ON order_items (order_id);